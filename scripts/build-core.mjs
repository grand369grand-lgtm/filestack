/**
 * Builds the Rust core for wasm and inlines it into the JS bundle.
 *
 *   node scripts/build-core.mjs
 *
 * Inlining (base64) instead of fetching a .wasm asset means the app works
 * offline, in Expo Go, and inside sandboxed web previews with no network.
 */
import { execSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const crateDir = resolve(root, 'rust');
const wasmPath = resolve(crateDir, 'target/wasm32-unknown-unknown/release/filecore.wasm');
const outPath = resolve(root, 'src/core/filecore.generated.ts');

const skipBuild = process.argv.includes('--skip-build');

if (!skipBuild) {
  console.log('▸ cargo build --release --target wasm32-unknown-unknown');
  execSync('cargo build --release --target wasm32-unknown-unknown', {
    cwd: crateDir,
    stdio: 'inherit',
    env: { ...process.env, PATH: `${process.env.HOME}/.cargo/bin:${process.env.PATH}` },
  });
}

if (!existsSync(wasmPath)) {
  console.error(`✗ missing ${wasmPath}\n  Run: rustup target add wasm32-unknown-unknown`);
  process.exit(1);
}

const wasm = readFileSync(wasmPath);
const version =
  readFileSync(resolve(crateDir, 'Cargo.toml'), 'utf8').match(/^version\s*=\s*"([^"]+)"/m)?.[1] ??
  '0.0.0';
const sha = createHash('sha256').update(wasm).digest('hex').slice(0, 16);

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(
  outPath,
  `// AUTO-GENERATED by scripts/build-core.mjs — do not edit.
// source: rust/  version: ${version}  sha256: ${sha}
export const FILECORE_META = {
  version: ${JSON.stringify(version)},
  sha256: ${JSON.stringify(sha)},
  bytes: ${wasm.length},
  target: 'wasm32-unknown-unknown',
} as const;

export const FILECORE_WASM_BASE64 =
  '${wasm.toString('base64')}';
`,
);

console.log(
  `✓ src/core/filecore.generated.ts  (${(wasm.length / 1024).toFixed(1)} KB wasm, ` +
    `${(readFileSync(outPath).length / 1024).toFixed(0)} KB inlined, v${version})`,
);
